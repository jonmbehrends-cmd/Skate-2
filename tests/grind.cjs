const assert=require('node:assert/strict');
require('../grind.js');
const {find,attach,advance,visualYaw}=globalThis.SOLGrind;
const rails=[{x:0,z:10,len:8,y:1.1}];
function state(overrides={}){return {x:0,z:10,y:1.19,vy:-5,dir:0,speed:8,grounded:false,grinding:false,grindCooldown:0,combo:100,grindTime:0,...overrides}}
const dt=.025;
const hit=find(state(),rails,dt,true);
assert(hit&&hit.rail===rails[0],'Descending stable board must contact rail');
assert(!find(state({y:5}),rails,dt,true),'Cannot teleport down from high above');
assert(!find(state({y:.8}),rails,dt,true),'Cannot attach from below');
assert(!find(state({vy:2}),rails,dt,true),'Rising skater cannot attach');
assert(!find(state({vy:2}),rails,dt,true,true),'Assisted grind must not attach on ascent');
assert(!find(state({dir:Math.PI/2}),rails,dt,true),'Perpendicular travel must not grind');
assert(!find(state({x:.5}),rails,dt,true),'Too much lateral offset');
assert(find(state({x:.5}),rails,dt,true,true),'GRIND button should widen lateral catch without changing passive contact');
assert(!find(state({z:14}),rails,dt,true),'Outside rail endpoint');
assert(!find(state({speed:1}),rails,dt,true),'Too slow to grind');
assert(!find(state({grindCooldown:.1}),rails,dt,true),'Cooldown blocks immediate reattachment');
assert(!find(state(),rails,dt,false),'Incomplete board rotation blocks grind');
const s=state();assert(attach(s,hit));
assert(s.grinding&&!s.grounded&&s.y===1.1&&s.vy===0);
const speed=s.speed,combo=s.combo;
assert.equal(advance(s,.025),false);
assert(s.speed<speed&&s.combo>combo,'Grinding consumes speed and builds combo');
assert.equal(s.x,0,'Grind remains constrained to rail');
s.z=13.9;assert.equal(advance(s,.025),true,'Rail endpoint releases board');
assert(!s.grinding&&!s.grounded&&s.grindRail===null&&s.grindCooldown>0);
const reverse=state({dir:Math.PI}),back=find(reverse,rails,dt,true);
assert(back&&back.direction===-1,'Reverse-direction grinds supported');
attach(reverse,back);assert(Math.abs(reverse.dir-Math.PI)<1e-9);
// A boardslide must put the deck sideways over the rail without rotating the
// movement vector away from the rail, and must cleanly restore normal riding.
const board=state({x:.1,grindRequestType:'boardslide'});
const boardHit=find(board,rails,dt,true,true);
assert(boardHit,'Assisted boardslide must catch a descending board');
const boardDir=board.dir;
assert(attach(board,boardHit),'Boardslide attachment should succeed');
assert.equal(board.grindType,'boardslide');
assert.equal(board.grindRequestType,null,'Boardslide request must be consumed');
assert(Math.abs(visualYaw(board)-Math.PI/2)<1e-9,'Board must sit 90 degrees across the rail');
assert.equal(board.dir,boardDir,'Physical travel direction must stay along the rail');
const boardScore=board.combo;
advance(board,.025);
assert(board.combo>boardScore,'Boardslide must score during rail travel');
board.z=13.95;
assert.equal(advance(board,.025),true,'Boardslide releases at the rail endpoint');
assert.equal(visualYaw(board),0,'Board rotation must reset after leaving rail');
assert.equal(board.grindSide,null,'Approach-side state must be cleared');
const other=state({x:-.1,grindRequestType:'boardslide'});
assert(attach(other,find(other,rails,dt,true,true)));
assert(Math.abs(visualYaw(other)+Math.PI/2)<1e-9,'Opposite-side boardslides rotate the other way');
const ordinary=state({grindRequestType:'50-50'});
assert(attach(ordinary,find(ordinary,rails,dt,true)));
assert.equal(visualYaw(ordinary),0,'Standard 50-50 must remain lengthwise');
// The 100-foot bowl has a single circular coping rail, not four straight rails.
const bowlRail={x:0,z:-106,radius:15.24,y:.09,kind:'bowl-coping'};
require('../bowl.js');
const bowlWallY=globalThis.SOLBowl.height(15.10,-106);
const bowlState=state({x:15.10,z:-106,y:bowlWallY,groundY:bowlWallY,vy:0,dir:Math.PI/2,grounded:true,speed:8,grindCooldown:0,grindRequestType:'50-50'});
const bowlHit=find(bowlState,[bowlRail],dt,true,true);
assert(bowlHit&&bowlHit.rail===bowlRail,'Grounded GRIND button must find bowl coping on a radial approach');
assert(attach(bowlState,bowlHit),'Bowl coping attachment must succeed without an ollie');
assert.equal(bowlState.vy,0,'Bowl coping GRIND must not force an ollie');
const bx=bowlState.x,bz=bowlState.z;
for(let i=0;i<60;i++)advance(bowlState,1/60);
assert(bowlState.grinding,'Circular coping should remain engaged for at least one second');
assert(Math.hypot(bowlState.x-bx,bowlState.z-bz)>3,'Skater must travel around the coping');
assert(Math.abs(Math.hypot(bowlState.x,bowlState.z+106)-bowlRail.radius)<.01,'Coping grind must follow the exact bowl radius');
console.log('PASS: rail contact height, direction, speed, cooldown, board stability, traversal, and exit');
