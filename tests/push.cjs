const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]).filter(x=>x.trim());
assert.equal(inline.length,1);
new vm.Script(inline[0]);
assert(html.includes('src="skater.js"'));
assert(inline[0].includes('SOLSkater.pose(state,boost||pushHeld||now<(state.pushBurstUntil||0),now,steer)'));
assert(inline[0].includes('body.rotation.y=pose.torsoYaw'));
assert(inline[0].includes('legs[i].rotation.x=back?pose.backHip:pose.frontHip'));
const context={};vm.runInNewContext(fs.readFileSync('skater.js','utf8'),context);
const pose=context.SOLSkater.pose;
const base={grounded:true,grinding:false,speed:3,vy:0,pushPhase:1.4};
const ride=pose(base,false,250,0),push=pose(base,true,250,0);
assert.equal(ride.pushing,false);
assert.equal(ride.torsoYaw,Math.PI/2);
assert.equal(push.pushing,true);
assert(push.contact>0);
assert.equal(pose({...base,pushPhase:0},true,250,0).contact,0);
assert(pose({...base,pushPhase:Math.PI*1.5},true,250,0).recovery>0);
assert(push.backHip!==push.frontHip);
assert(push.backKnee>push.frontKnee);
assert.equal(pose({...base,grounded:false},true,250,0).pushing,false);
assert.equal(pose({...base,grinding:true},true,250,0).pushing,false);
assert.equal(pose({...base,speed:15},true,250,0).pushing,false);
assert.equal(pose(base,false,250,0).backOffset,0);
console.log('Skater stance, push cycle, air/grind gating and inline integration PASS');

const rampPose=pose({...base,onRamp:true,pumpIntensity:.8},true,250,0);
assert.equal(rampPose.pushing,false,'Ramp pumping must not trigger a foot push');
assert(rampPose.crouch>ride.crouch,'Pumping compression must bend rider');
assert(inline[0].includes('stanceRig.rotation.x=riding?boardPivot.rotation.x:0'),'Rider must follow board slope');
assert(inline[0].includes('const snap=riding&&!state.wasVisualGrounded'),'Landing must snap board to grounded contact');
console.log('PASS: rider follows slope, lands level, ramp compression distinct from foot pushing');
