// Parse the actual inline game source without requiring a browser or the Babylon CDN.
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('index.html','utf8');
const scripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x => x[1]).filter(x => x.trim());
assert.equal(scripts.length, 1, 'Expected exactly one inline game script');
for(const source of scripts) new vm.Script(source,{filename:'index.html:inline'});
assert(html.includes('src="controller.js'), 'Controller module must load');
assert(html.includes("camera.lockedTarget=cameraAnchor"),'Follow camera must use independent heading anchor, not spinning skater');
assert(html.includes('cameraAnchor.rotation.y=state.airCameraHeading'),'Camera yaw must be driven by independent heading, not the skater spin');
assert(html.includes('if(riding){const travelHeading=')&&html.includes('state.airCameraHeading+=delta'),'Chase camera must follow travel direction on ground and freeze heading in the air');
assert(html.includes('skater.rotation.y=state.dir'),'Skater mesh must visibly rotate in air');
assert(html.includes('src="landing.js'), 'Landing module must load');
assert(html.includes('src="terrain.js'), 'Terrain module must load');
assert(html.includes('src="ramp_geometry.js'), 'Sealed ramp mesh module must load');
assert(html.includes('src="obstacles.js'), 'Obstacle module must load');
assert(html.includes('src="grind.js'), 'Rail grind module must load');
assert(html.includes('src="motion.js'), 'Momentum module must load');
assert(html.includes('src="wheels.js'), 'Wheel contact module must load');
assert(html.includes('SOLWheels.sample(state.x,state.z,state.dir,state.y,groundContact)'), 'Four-wheel support must drive visual board pose');
assert(html.includes('SOLWheels.relativeImpact(state,0,contact.slope)'), 'Slope-relative impact must use airborne velocity');
assert(html.includes('SOLMotion.step(state,steer,throttle,boost||pushHeld||now<(state.pushBurstUntil||0),dt)'), 'Ground/air controls must use deterministic motion module with push input');
assert(html.includes('SOLMotion.horizontal(state,dt)'), 'Horizontal airborne velocity must be decoupled from facing');
assert(html.includes('SOLMotion.collide(state,[swept,side,bounds])'), 'Obstacle and park-edge impacts must update airborne vector velocity');
assert(html.includes('SOLMotion.beginAir(state)'), 'Takeoffs must lock horizontal velocity');
assert(html.includes('SOLMotion.landingAlignment(state)'), 'Landing must validate heading versus velocity');
assert(html.includes('SOLGrind.find('), 'Rail entry must use height-aware grind detection');
assert(html.includes('SOLGrind.advance('), 'Rail travel must use constrained grind simulation');
assert(html.includes('grindCooldown'), 'Rail dismount cooldown must be wired');
assert(html.includes('SOLObstacles.sweep('), 'Swept collision must be integrated');
assert(html.includes('SOLObstacles.surface('), 'Elevated platforms must be integrated');
assert(html.includes('SOLObstacles.rampSide('), 'Ramp side collision must be integrated');
assert(html.includes('previousContact.height>contact.height'), 'Platform edges must drop instead of snapping');
assert(html.includes('SOLTerrain.sample('), 'Terrain sampling must be integrated');
assert(html.includes('SOLTerrain.launch('), 'Lip launch must be integrated');
assert(html.includes("new B.Mesh('solid skatable concrete ramp'") && html.includes('vd.applyToMesh(mesh)') && html.includes('SOLRampGeometry.build(r,SOLTerrain.profile,N)'), 'Ramps must render as sealed shared-profile curved WebGL meshes');
assert(html.includes('SOLTerrain.profile(r,t)'), 'Mesh must share contact profile');
assert(html.includes('Math.ceil(elapsed/.025)'), 'Simulation must substep slow frames');
assert(html.indexOf('src="controller.js') < html.indexOf('src="landing.js'), 'Controller precedes landing module');
assert(html.includes('SOLLanding.canLand(state,state.flip,state.spin)'), 'Landing physics must be integrated');
assert(html.includes('legacy.html'), 'Legacy fallback must remain');
console.log('SOL SKATE inline game script and module wiring passed');
