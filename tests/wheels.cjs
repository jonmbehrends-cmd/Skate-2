const assert=require('node:assert/strict');
require('../wheels.js');
const {sample,relativeImpact}=globalThis.SOLWheels;
const plane=(x,z)=>({height:2+.2*x+.3*z});
const flat=sample(0,0,0,0,()=>({height:0}));
assert.equal(flat.height,0);assert.equal(flat.pitch,0);assert.equal(flat.roll,0);
const uphill=sample(0,0,0,2,plane);
assert(Math.abs(uphill.pitch+Math.atan(.3))<1e-10,'Forward slope must pitch board uphill');
assert(Math.abs(uphill.roll-Math.atan(.2))<1e-10,'Side slope must roll board toward high wheels');
assert(Math.abs(uphill.height-2)<1e-10,'Plane support must match center height');
const turned=sample(0,0,Math.PI/2,2,plane);
assert(Math.abs(turned.pitch+Math.atan(.2))<1e-10,'Pitch follows board heading');
assert(Math.abs(turned.roll+Math.atan(.3))<1e-10,'Roll follows right side of board');
const ledge=sample(0,0,0,0,(x)=>({height:x>.2?.7:0}));
assert(ledge.roll>0,'Single-sided ledge must bank board');
for(const p of ledge.points)assert(ledge.height+ledge.forwardSlope*p.forward+ledge.sideSlope*p.side>=p.height-1e-9,'Rigid support must not penetrate wheel surface');
const moving={vy:-3,dir:Math.PI/2,speed:8,airVX:0,airVZ:10};
assert.equal(relativeImpact(moving,0,.3),-6,'Landing impact uses actual travel, not facing');
assert.equal(relativeImpact({...moving,airVX:null,airVZ:null},0,.3),-3,'Facing fallback for legacy state');
console.log('PASS: four-wheel plane fit, rotated heading, ledge clearance, slope-relative landing');
